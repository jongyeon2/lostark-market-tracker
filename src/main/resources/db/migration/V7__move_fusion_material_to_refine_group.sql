-- 융화 재료를 강화재료 -> 재련재료로 재분류하고 강화재료 그룹을 폐지한다 (요청 2번).
--
-- 왜 마이그레이션이 필요한가: WatchlistSeeder는 insert-if-absent다
-- (findByExternalItemId(...).orElseGet(insert)) — "Phase 4 admin CRUD가 나중 편집을 소유"하므로
-- 기존 행을 의도적으로 건드리지 않는다. 따라서 시더 소스의 item_group만 고치면 이미 존재하는
-- 아비도스 융화 재료 행(운영: id=1 6861012, id=2 6861013)은 영원히 '강화재료'로 남고,
-- 프론트에서 강화재료 leaf만 사라져 두 품목이 어느 카테고리에도 안 걸린 채 대시보드에서
-- 조용히 사라진다. 기존 행을 옮길 수 있는 경로는 이 마이그레이션뿐이다.
--
-- id가 아니라 group 기준인 이유: 폐지 대상은 '강화재료' 카테고리 자체다. 그룹 기준이라
-- 시더에 없는 레거시 행(dev DB의 오레하 융화 재료 6861009/6861011 — 과거 seed 잔재)까지
-- 함께 이동해 어느 환경에서도 그룹이 확실히 비고, 재실행해도 대상이 0건이라 멱등하다.
--
-- 도메인 근거: 융화 재료는 재련(강화)에 반드시 들어가는 재료다. 별도 카테고리로 분리할 이유가 없다.
UPDATE tracked_item
SET item_group = '재련재료'
WHERE item_group = '강화재료';
