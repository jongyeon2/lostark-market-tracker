/** 대륙 leaf 하나: 라벨과 그에 속한(=거래소에 실제로 있는) 아이템들. */
export interface ContinentGroup {
  name: string
  items: MarketSearchItem[]
}

/**
 * 서버가 준 모험의 서 전량을 대륙 leaf로 묶는다.
 *
 * **서버 응답이 단일 출처다.** 표에만 있고 거래소에 없는 이름은 그리지 않는다(빈 줄이 남을 이유가
 * 없다). 반대로 **거래소에 새로 등장했는데 표에 없는 아이템은 버리지 않고** `미분류` leaf에 담는다 —
 * 대륙이 추가되는 날 그 7개가 조용히 사라지는 게 최악이고, 대륙을 모르더라도 시세는 볼 수 있다.
 * 이때 `미분류`가 눈에 보이는 것 자체가 "표를 갱신하라"는 신호다.
 *
 * 아이템이 하나도 없는 대륙은 leaf를 만들지 않는다(대시보드 deriveCategories 선례).
 */
export function groupByContinent(items: readonly MarketSearchItem[]): ContinentGroup[] {
  const byName = new Map<string, MarketSearchItem[]>()
  for (const item of items) {
    const bucket = byName.get(item.name)
    if (bucket) bucket.push(item)
    else byName.set(item.name, [item])
  }

  const groups: ContinentGroup[] = []
  const claimed = new Set<string>()
  for (const continent of CONTINENTS) {
    const found: MarketSearchItem[] = []
    for (const name of continent.items) {
      const matches = byName.get(name)
      if (matches) {
        found.push(...matches)
        claimed.add(name)
      }
    }
    if (found.length > 0) {
      groups.push({ name: continent.name, items: found })
    }
  }

  const unmapped = items.filter((i) => !claimed.has(i.name))
  if (unmapped.length > 0) {
    groups.push({ name: UNMAPPED_LABEL, items: unmapped })
  }
  return groups
}
