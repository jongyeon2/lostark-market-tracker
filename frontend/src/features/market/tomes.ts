/*
  모험의 서 수집품의 대륙 분류표 (단일 출처).

  🔑 왜 하드코딩인가: 로스트아크 API는 이 분류를 어디서도 주지 않는다(실측 2026-07-20).
  `/markets/options`의 카테고리 `100000 모험의 서`는 **Subs가 빈 배열**이고 대륙 필터 파라미터도
  없다. 아이템 이름에도 대륙 표시가 없다("니바르의 손"이 욘이라는 건 이름만 봐선 모른다).
  웹 조사도 전부 실패했다 — 공식 게임가이드는 대륙 이름조차 나열하지 않고, 공식 공략글·나무위키·
  인벤·블로그 어디에도 "거래 가능한 대륙별 수집품 목록"이 없다.

  그래서 출처는 **사용자가 인게임 모험의 서를 직접 열어 정리한 목록**이다. 그대로 믿지 않고
  거래소 전량(14페이지)과 대조했다:
  - 20대륙 × 7개 = 140 == 거래소 `TotalCount` 140, 중복 0, 누락 0
  - 136개는 문자열까지 동일
  - 4개만 표기가 달랐고(루페온 시상→신상 / 태양 소금→태양소금 / 사피라 연구 일지→연구일지 /
    엘조원→엘조윈) 남은 미매칭 4개와 1:1로 대응됐다 — 일대일이라 다른 해석의 여지가 없다.

  매칭 키가 아이템 **이름**이므로 아래는 전부 거래소 표기다. 인게임 표기와 다르더라도 고치지 말 것 —
  고치는 순간 그 아이템이 목록에서 사라지고 `미분류`로 떨어진다.

  순서 = 게임 진행 순서(아르테미스 → … → 림레이크 남섬).
*/

